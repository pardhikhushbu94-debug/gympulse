/**
 * Generates formatted CSV string for accounting & GST filing
 */
export function generateGSTReportCSV(members: AdminMemberRecord[]): string {
  const headers = [
    'MemberID',
    'CustomerName',
    'MobileNumber',
    'PlanSubscribed',
    'TaxableBaseINR',
    'CGST_9_Pct',
    'SGST_9_Pct',
    'TotalInvoiceINR',
    'PaymentMode',
    'ExpiryDate',
    'Status',
  ];

  const rows = members.map((m) => {
    // 18% GST calculation (base = total / 1.18)
    const base = Math.round(m.amountPaidINR / 1.18);
    const cgst = Math.round((m.amountPaidINR - base) / 2);
    const sgst = m.amountPaidINR - base - cgst;

    return [
      m.id,
      `"${m.name}"`,
      m.phone,
      `"${m.planName}"`,
      base,
      cgst,
      sgst,
      m.amountPaidINR,
      m.paymentMethod.toUpperCase(),
      m.expiryDate,
      m.status.toUpperCase(),
    ].join(',');
  });

  return [headers.join(','), ...rows].join('\n');
}
